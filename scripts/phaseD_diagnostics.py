"""Phase-D self-training diagnostics on `peru-dev` (METHODS_NOTES 2026-10-15: self-training
results entry, its correction and addendum). Replaces the inline analyses run that day.

1. Paired per-seed IoU deltas vs the same source seed, from outputs/phaseD/dev_table_runs.csv
   (run scripts/phaseD_dev_table.py first) → outputs/phaseD/paired_deltas.csv.
2. Teacher water fraction on pool batches during training (`target/water_frac_ema` in each
   run's metrics.csv) at iterations 100, 1,000, 2,000 and the last → water_frac_trajectory.csv.
   `first` = the first logged value (a single batch, before smoothing has any effect).
3. Predicted dev water fraction (logit > 0) over every dev pixel (ignore pixels, label −1,
   count as non-water; the same denominator for every row) for source, `st`, `mic` and their
   no-AdaBN diagnostics, plus the label water fraction → dev_water_fraction.csv.
4. Seed-0 oracle grid without AdaBN (post-hoc): pooled IoU / precision / recall of
   outputs/logits_dev/st*_noadabn/<model>/seed0 → oracle_grid_noadabn.md.

    uv run python scripts/phaseD_diagnostics.py
"""

from pathlib import Path

import numpy as np
import pandas as pd
import rasterio

from floodseg.metrics import counts, scores

REPO = Path(__file__).resolve().parents[1]
PERU = REPO / "data" / "peru" / "unosat2023"
LOGITS = REPO / "outputs" / "logits_dev"
OUT = REPO / "outputs" / "phaseD"
MODELS = ["unet", "terramind_v1_base"]
SEEDS = ["seed0", "seed1", "seed2"]


def paired_deltas() -> None:
    d = pd.read_csv(OUT / "dev_table_runs.csv")
    regs = ["s1f11_src", "adabn", "hm", "st", "mic", "st_noadabn", "mic_noadabn"]
    p = d[d.regime.isin(regs)].pivot_table(index=["model", "seed"], columns="regime", values="iou")
    for r in regs[1:]:
        if r in p:
            p[f"d_{r}"] = p[r] - p["s1f11_src"]
    p.round(4).to_csv(OUT / "paired_deltas.csv")
    print(p.round(4).to_string(), "\n")


def water_frac_trajectory() -> None:
    rows = []
    for f in sorted((OUT / "self_train").glob("*/*/seed*/metrics.csv")):
        if "demo" in f.parts[-4]:
            continue
        c = pd.read_csv(f)[["step", "target/water_frac_ema"]].dropna()

        def at(s):
            return float(c.iloc[(c.step - s).abs().argsort()[:1]]["target/water_frac_ema"].iloc[0])

        rows.append(dict(run="/".join(f.parts[-4:-1]), first=float(c["target/water_frac_ema"].iloc[0]),
                         it100=at(100), it1000=at(1000), it2000=at(2000), it4000=at(c.step.max())))
    df = pd.DataFrame(rows)
    df.to_csv(OUT / "water_frac_trajectory.csv", index=False)
    print(df.round(4).to_string(index=False), "\n")


def dev_scans() -> None:
    stems = (PERU / "splits" / "dev.txt").read_text().split()
    frac_dirs = [LOGITS / r / m / s for r in ["s1f11_src", "st", "mic", "st_noadabn", "mic_noadabn"] for m in MODELS for s in SEEDS]
    grid_dirs = sorted(LOGITS.glob("st*_noadabn/*/seed0"))
    for d in frac_dirs + grid_dirs:
        assert len(list(d.glob("*.npy"))) == len(stems), d
    total = water = 0
    pred = {d: 0 for d in frac_dirs}
    cnt = {d: np.zeros((2, 3), np.int64) for d in grid_dirs}
    for st in stems:
        with rasterio.open(PERU / "label" / f"{st}.tif") as f:
            y = f.read(1)
        total += y.size
        water += int((y == 1).sum())
        for d in frac_dirs:
            pred[d] += int((np.load(d / f"{st}.npy") > 0).sum())
        for d in grid_dirs:
            cnt[d] += counts(np.load(d / f"{st}.npy") > 0, y)
    rows = [dict(regime="label", model="-", seed="-", water_frac=water / total)]
    rows += [dict(regime=d.parts[-3], model=d.parts[-2], seed=d.parts[-1], water_frac=v / total) for d, v in pred.items()]
    df = pd.DataFrame(rows)
    df.to_csv(OUT / "dev_water_fraction.csv", index=False)
    print(df.round(4).to_string(index=False), "\n")

    lines = ["| Backbone | regime (seed 0, final teacher, no AdaBN) | IoU | precision | recall |", "|---|---|---|---|---|"]
    for d in grid_dirs:
        s = scores(cnt[d])
        lines.append(f"| {d.parts[-2]} | {d.parts[-3]} | {s['iou']:.4f} | {s['precision']:.4f} | {s['recall']:.4f} |")
    text = ("Post-hoc diagnostic (not pre-registered): seed-0 grid, final teacher iter 4000 without the AdaBN "
            "pass. Generated by scripts/phaseD_diagnostics.py.\n\n" + "\n".join(lines) + "\n")
    (OUT / "oracle_grid_noadabn.md").write_text(text)
    print(text)


if __name__ == "__main__":
    paired_deltas()
    water_frac_trajectory()
    dev_scans()
