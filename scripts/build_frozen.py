"""Write `configs/frozen.yaml`: the configurations approved for the one-time test evaluation
(phase-D task 6.1, plan-flood-research 7.2; decision in docs/METHODS_NOTES.md 2026-10-16
"Phase-D freeze").

Each group is one row of the results table (logit folder `regime`, backbone `model`) with its
3 seed checkpoints. For every checkpoint: path, sha256, and the training run's git commit from
its run record. Shared fitted artifacts (pool manifest, test-time HM map, temperatures, label-QA
table) are listed with their sha256. `pass` says which evaluation pass scores the group:
`phaseD` (peru-test, peru-2017-test now) or `section7` (frozen now, scored later; disk space).
scripts/evaluate_frozen.py refuses held-out splits for anything not listed here.

    uv run python scripts/build_frozen.py
"""

import glob
import json
from pathlib import Path

import yaml

from floodseg.target_pool import REPO, sha256

# regime, model, run folder, method applied at evaluation, role, pass, dev water IoU (3 seeds, docs/phaseD_dev.md)
GROUPS = [
    ("trhm", "unet", "s1f11_trhm_unet", "none", "primary", "phaseD", "0.9118 ± 0.0026"),
    ("trfda", "terramind_v1_base", "s1f11_trfda_terramind_v1_base", "none", "primary", "phaseD", "0.8365 ± 0.0010"),
    ("s1f11_src", "prithvi_eo_v2_300", "s1f11_src_prithvi", "none", "primary", "phaseD", "0.8701 ± 0.0011"),
    ("trhm", "terramind_v1_base", "s1f11_trhm_terramind_v1_base", "none", "secondary", "phaseD", "0.8440 ± 0.0284"),
    ("adabn", "unet", "s1f11_src_unet", "adabn", "secondary", "phaseD", "0.8969 ± 0.0161"),
    ("hm", "terramind_v1_base", "s1f11_src_terramind_lr5e-5", "hm_test", "secondary", "phaseD", "0.8089 ± 0.0064"),
    ("s1f11_src", "unet", "s1f11_src_unet", "none", "reference", "phaseD", "0.8364 ± 0.0224"),
    ("s1f11_src", "terramind_v1_base", "s1f11_src_terramind_lr5e-5", "none", "reference", "phaseD", "0.7027 ± 0.0913"),
    ("peru", "unet", "runs_cloud", "none", "reference", "phaseD", "0.9415 ± 0.0019"),
    ("peru", "terramind_v1_base", "runs_cloud", "none", "reference", "phaseD", "0.9265 ± 0.0025"),
    ("peru", "prithvi_eo_v2_300", "runs_cloud", "none", "reference", "phaseD", "0.9218 ± 0.0006"),
    ("s1f11_ft", "unet", "runs_cloud_s1f11_ft", "none", "reference", "section7", "0.9383 ± 0.0018"),
    ("s1f11_ft", "terramind_v1_base", "runs_cloud_s1f11_ft", "none", "reference", "section7", "0.9282 ± 0.0009"),
    ("s1f11_ft", "prithvi_eo_v2_300", "runs_cloud_s1f11_ft", "none", "reference", "section7", "0.9236 ± 0.0006"),
]
ARTIFACTS = {
    "pool_manifest": "configs/pools/peru-train.csv",
    "hm_test_params": "outputs/phaseD/alignment/params.npz",
    "temperatures_phaseD": "outputs/phaseD/analysis/temperatures.json",
    "temperatures_peru": "outputs/analysis_dev/temperatures_valid.json",
    "label_qa_chips": "outputs/label_qa/chips.csv",
}


def main() -> None:
    groups = []
    for regime, model, folder, method, role, pas, dev in GROUPS:
        runs = {}
        for seed in (0, 1, 2):
            d = REPO / "outputs" / folder / model / "lightning_logs" / f"seed{seed}"
            ck = glob.glob(str(d / "checkpoints" / "best-*.ckpt"))
            assert len(ck) == 1, f"{d}: {ck}"
            ck = Path(ck[0])
            rec = json.loads((d / "run.json").read_text())
            runs[f"seed{seed}"] = dict(checkpoint=str(ck.relative_to(REPO)), sha256=sha256(ck),
                                       train_commit=rec["git"]["commit"], train_dirty=rec["git"]["dirty"])
            print(regime, model, seed, runs[f"seed{seed}"]["sha256"][:12], flush=True)
        groups.append(dict(id=f"{regime}/{model}", regime=regime, model=model, method=method, role=role,
                           **{"pass": pas}, dev_water_iou=dev, runs=runs))
    doc = dict(
        frozen_on="2026-10-16",
        decision='docs/METHODS_NOTES.md, 2026-10-16 "Phase-D freeze for the one-time test evaluation"',
        prediction="water if z = logit_water - logit_other > 0 (no threshold tuning)",
        artifacts={k: dict(path=v, sha256=sha256(REPO / v)) for k, v in ARTIFACTS.items()},
        groups=groups,
    )
    out = REPO / "configs" / "frozen.yaml"
    out.write_text("# Generated by scripts/build_frozen.py. Do not edit by hand.\n"
                   + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=120))
    print(f"wrote {out.relative_to(REPO)}: {len(groups)} groups, {3 * len(groups)} runs")


if __name__ == "__main__":
    main()
